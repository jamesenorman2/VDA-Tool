// Verification against the NPSA Vehicle Dynamics Assessment tool.
// Defines the test routes, computes this tool's expected speeds, and writes
// docs/verification/npsa-check.md (instructions, a prompt for Claude in Chrome, expected values).
// Run: npm run verify:cases
import { writeFileSync } from 'node:fs';
import { VEHICLES, buildRouteSpeeds } from '../src/maths.js';
import { VERSION } from '../src/version.js';

// Sections listed from the START of the route to the ASSET. s = straight (length m),
// l / r = left / right curve (arc length m, radius m). Chosen to cross every acceleration band
// break (20, 55, 105, 280, 440 m) and every class's slip radius (61–150 m).
export const CASES = [
  { id: 'C01', why: 'Short straight: car changes acceleration band at 20 m', sections: [['s', 20]] },
  { id: 'C02', why: 'Flatbed band change at 55 m', sections: [['s', 55]] },
  { id: 'C03', why: 'Pick-up band change at 105 m', sections: [['s', 105]] },
  { id: 'C04', why: '18 t rigid band change at 280 m', sections: [['s', 280]] },
  { id: 'C05', why: 'Beyond 440 m: every class at top speed', sections: [['s', 500]] },
  { id: 'C06', why: 'Tight bend only (10 m radius)', sections: [['l', 30, 10]] },
  { id: 'C07', why: 'Straight, 25 m right bend, straight', sections: [['s', 100], ['r', 40, 25], ['s', 60]] },
  { id: 'C08', why: '60 m bend: just under the 18 t slip radius (60.6 m)', sections: [['s', 150], ['l', 50, 60], ['s', 100]] },
  { id: 'C09', why: '95 m bend: between 7.5 t (88.7 m) and 30 t / flatbed slip radii (99.7 / 101 m)', sections: [['s', 200], ['r', 60, 95], ['s', 50]] },
  { id: 'C10', why: '145 m bend: above the pick-up slip radius (139 m), below 150 m', sections: [['s', 120], ['l', 80, 145], ['s', 30]] },
  { id: 'C11', why: 'S-bend of two 15 m bends', sections: [['s', 80], ['l', 20, 15], ['s', 10], ['r', 20, 15], ['s', 70]] },
  { id: 'C12', why: 'Mixed route ending in a long straight', sections: [['s', 60], ['r', 35, 40], ['s', 90], ['l', 25, 20], ['s', 150], ['r', 45, 75], ['s', 40]] },
  { id: 'C13', why: 'Bend right at the asset (speed limited by the last section)', sections: [['s', 300], ['r', 20, 30]] },
];
export const STARTS = ['STANDING', 'ROLLING'];

const TYPE = { s: 'STRAIGHT', l: 'CURVE_LEFT', r: 'CURVE_RIGHT' };
// Engine wants nearest-asset first.
export const toSections = (c) => c.sections.map(([t, len, radius]) => ({ sType: TYPE[t], sLength: len, radius: radius ?? 150 })).reverse();
export function expected(c, start) {
  const row = buildRouteSpeeds(toSections(c), start)[0].exitSpeeds;
  return Object.fromEntries(VEHICLES.map((v) => [v.id, row.get(v.id).speed]));
}
const sectionText = ([t, len, r]) => (t === 's' ? `Straight ${len} m` : `${t === 'l' ? 'Left' : 'Right'} curve, length ${len} m, radius ${r} m`);
// Start of route → asset (this tool's order).
const describe = (c) => c.sections.map((x, i) => `${i + 1}. ${sectionText(x)}`).join('; ');
// HOVVA's order: starting at the asset and working back to the start of the route.
const describeHovva = (c) => [...c.sections].reverse().map((x, i, a) => `${i + 1}. ${sectionText(x)}${i === 0 ? ' (at the asset)' : ''}${i === a.length - 1 && a.length > 1 ? ' (start of route)' : ''}`).join('; ');

if (import.meta.url === `file://${process.argv[1]}`) {
  const cls = VEHICLES.map((v) => v.name);
  let md = `# Checking speeds against NPSA HOVVA

Generated by \`npm run verify:cases\` from VDA Tool v${VERSION}. Each test route below is entered into the NPSA tool with both a standing and a rolling start, and the speed at the asset is read for every vehicle class. Then the results are compared with this tool's figures (last section of this page).

The routes cross every acceleration band change (20, 55, 105, 280 and 440 m) and every class's slip radius, so if they all match, the engines agree.

## Step 1: give this prompt to Claude in Chrome

Open NPSA HOVVA in Chrome, sign in, then paste this into Claude in Chrome. Check first that the site's terms allow automated use. If they don't, a person can follow the same steps.

\`\`\`text
I am verifying another tool against NPSA HOVVA (the vehicle dynamics assessment tool) open in this tab.
For EACH test route below, and for EACH start condition (standing, then rolling):
1. Clear any existing route sections.
2. Set speed units to km/h.
3. Set the route start to the given condition (standing = vehicles stationary, rolling = vehicles at maximum speed).
4. Enter the sections EXACTLY IN THE ORDER GIVEN. They are already in HOVVA's order: section 1 is
   at the asset, and the last section is the start of the route. Do not reverse them.
   Curves give arc length and radius. Left/right is the driver's left/right when driving
   towards the asset, as in HOVVA.
5. Read the speed AT THE ASSET for each of the six vehicle classes, exactly as displayed.
Do not change anything else and do not round or convert. If a route cannot be entered, say why and continue.
When all are done, output ONLY a CSV block with this header and one line per route and start:
case,start,${cls.map((c) => `"${c}"`).join(',')}

Test routes:
${CASES.map((c) => `${c.id}: ${describeHovva(c)}`).join('\n')}
\`\`\`

## Step 2: compare

Paste the CSV that Claude in Chrome returns into this chat, or save it as \`docs/verification/npsa-results.csv\` and run \`npm run verify:compare\`. Every difference is listed. Differences of up to 1 km/h are expected from rounding; anything larger points to a real difference in the engines.

## This tool's expected speeds at the asset (km/h)

| Case | Start | ${cls.join(' | ')} |
|---|---|${cls.map(() => '---:').join('|')}|
`;
  for (const c of CASES) for (const st of STARTS) {
    const e = expected(c, st);
    md += `| ${c.id} | ${st === 'STANDING' ? 'Standing' : 'Rolling'} | ${VEHICLES.map((v) => `${Math.round(e[v.id])} (${e[v.id].toFixed(1)})`).join(' | ')} |\n`;
  }
  md += `\nWhole numbers are what this tool displays; the figure in brackets is the unrounded value.\n\n## The test routes\n\nListed as entered in this tool (start of route → asset). The prompt above lists the same sections in HOVVA's order (asset first).\n\n${CASES.map((c) => `- **${c.id}** – ${c.why}. ${describe(c)}.`).join('\n')}\n`;
  writeFileSync(new URL('../docs/verification/npsa-check.md', import.meta.url), md);
  console.log('Wrote docs/verification/npsa-check.md');
}
